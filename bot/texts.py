def reminder_message(stage: int) -> tuple[str, InlineKeyboardMarkup]:
    builder = InlineKeyboardBuilder()
    if stage == 1:
        text = (
            "Вы в одном шаге от готового инструмента! ⏳\n\n"
            "Протокол диагностики шеи уже сформирован. Это не просто теория, а готовый "
            "пошаговый алгоритм, который поможет сразу показать клиенту экспертный уровень и "
            "забить график на месяцы вперед.\n\n"
            f"Подпишитесь на канал и откройте доступ:\n👉 {config.channel_url}"
        )
        builder.button(text="📥 Получить протокол диагностики", callback_data=CALLBACK_CHECK_ACCESS)
    else:
        text = (
            "Сарафанное радио строится на первом впечатлении 💡\n\n"
            "Если на первой встрече вы закрываете все вопросы клиента и точно объясняете "
            "биомеханику его проблемы — он остается тренироваться надолго и приводит "
            "знакомых.\n\n"
            "Не упускайте готовый инструмент для работы: забирайте бесплатный протокол "
            "диагностики шеи.\n\n"
            f"👉 {config.channel_url}"
        )
        builder.button(text="🎁 Забрать материал", callback_data=CALLBACK_CHECK_ACCESS)
    return text, builder.as_markup()
