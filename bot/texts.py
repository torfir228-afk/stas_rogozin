from aiogram.types import InlineKeyboardMarkup
from aiogram.utils.keyboard import InlineKeyboardBuilder

from bot.config import config

CALLBACK_CHECK_ACCESS = "check_access"


def welcome_message() -> tuple[str, InlineKeyboardMarkup]:
    text = (
        "Приветствую!\n\n"
        "Как получать постоянный поток клиентов без выгорания и ежедневного ведения "
        "социальных сетей?\n\n"
        "Каждый месяц к нам приходят 30–40 новых клиентов только по сарафанному радио. "
        "И это прямой результат проведения качественной первичной диагностики.\n\n"
        "После внедрения этого протокола вы:\n"
        "— Находите истинную причину боли и ограничений за 15–20 минут, а не гадаете на "
        "симптомах.\n"
        "— Сразу выстраиваете железобетонное доверие, закрывая клиента на полноценную "
        "тренировочную программу на несколько месяцев вперед, и забиваете свой график.\n"
        "— Получаете предсказуемый результат тренировок, о котором клиенты сами рассказывают "
        "знакомым.\n"
        "— Повышаете стоимость своих услуг за счет экспертного и доказательного подхода.\n\n"
        "Забирайте готовый протокол «Диагностика шеи» бесплатно прямо сейчас! 🎁"
    )
    builder = InlineKeyboardBuilder()
    builder.button(text="📥 Забрать диагностику бесплатно", callback_data=CALLBACK_CHECK_ACCESS)
    return text, builder.as_markup()


